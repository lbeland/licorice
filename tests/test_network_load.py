@pytest.mark.parametrize(
    "model, generator, validator, should_run_index",
    [
        (data_writer_model_int, int_values, validator_int, 0),
        (data_writer_model_messages, messages_values, validator_messages, 1),
        (data_writer_model_stress, stress_values, validator_stress, 2)
    ],
)
def test_udp_roundtrip(model, generator, validator, should_run_index, capfd):
    """
    Spawns a worker thread to send UDP packets to self machine at port.
    Terminate the worker thread with global should_run signal.
    Validate received packet data.

    Keyword Args:
        model (dict): Licorice Model
        generator (func): generator function that returns messages to be
            sent as UDP packets.
        validator (func): function to validate received UDP packet data.
            Assert False if error detected
        should_run_index (int): used to locate the should_run global
            control signal from should_run_arr
        capfd (Pytest object) : used to capture output and error

    Returns:
        None
    """
    global should_run_arr
    server_host = "localhost"
    server_port = 51002
    # Send data to the server using a separate thread
    client_thread = threading.Thread(
        target=send_udp_packets, args=(
            server_host, server_port, generator, should_run_index)
    )
    client_thread.start()
    licorice.go(
        model,
        confirm=True,
        working_path=f"{pytest.test_dir}/module_code",
        template_path=f"{pytest.test_dir}/templates",
    )

    should_run_arr[should_run_index] = False
    client_thread.join()

    # TODO: debug seg fault
    # validate_model_output(capfd, model["config"]["num_ticks"])
    output, outerr = capfd.readouterr()
    pattern = r"Timer thread started\.(.*?)^Killing module udp_"
    result = re.search(pattern, output, re.DOTALL | re.MULTILINE)
    extracted_content = result.group(1).strip()
    extracted_lines = extracted_content.split('\n')
    validator(extracted_lines)
