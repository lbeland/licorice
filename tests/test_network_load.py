should_run_arr = [True, True, True]


# sanity validator for edge cases
def validator_sanity(generated_values):

    if len(generated_values) == 0:
        print("Received no output. ")
        assert False
    if len(generated_values) == 1:
        print("Received 1 line of output: \"" + generated_values[0] + "\"")
        assert False


# generates sequential ints
def int_values():

    i = 0
    while True:
        yield struct.pack("Q", i)
        i += 1


def validator_int(generated_values):

    validator_sanity(generated_values)
    for i in range(len(generated_values)-1):
        try:
            if int(generated_values[i]) + 1 != int(generated_values[i+1]):
                print(f"Two values received are not sequential: \
                      \"{generated_values[i]}\" and \
                      \"{generated_values[i+1]}\".")
                assert False
        except ValueError:
            print("One of the values is not an int type between: \""
                  + generated_values[i] + '\" and \"'
                  + generated_values[i+1] + '\"')
            assert False


message_list = ["STAN", "FORD", "TREE", "MESS", "AGES"]
# generates repeating strings


def messages_values():

    i = 0
    global message_list
    while True:
        yield message_list[i % len(message_list)].encode("utf-8")
        i += 1


def validator_messages(generated_values):

    validator_sanity(generated_values)
    global message_list
    counter = {}
    for message in generated_values:

        if message not in message_list:
            print("Malformed message: \"" + message + "\"")
            assert False
        if message in counter:
            counter[message] += 1
        else:
            counter[message] = 1

    if (max(counter.values()) - min(counter.values())) > 1:
        print("Messages received distribution not balanced. See counter: ")
        print(counter)
        assert False


# MAX_UDP_PAYLOAD_LENGTH = 65507  # therotical max of UDP Payload only
UDP_PAYLOAD_LENGTH = 1500
# TODO: investigate and further test by making this a variable
stress_message = UDP_PAYLOAD_LENGTH * '#'
# generates a max data length UDP


def stress_values():

    i = 0
    while True:
        s = str(i)
        yield (s + stress_message[len(s):]).encode("utf-8")
        i += 1


def validator_stress(generated_values):

    validator_sanity(generated_values)
    for i in range(len(generated_values)-1):
        a = generated_values[i].strip('#')
        b = generated_values[i+1].strip('#')
        try:
            if int(a) + 1 != int(b):
                print(f"Two values received are not sequential: {a} and {b}.")
                assert False
        except ValueError:
            print("One of the values is not an int type between: "
                  + a + ' and ' + b)
            assert False


def send_udp_packets(
    interface="localhost",
    port=51002,
    generator=int_values,
    should_run_index=0
):

    """
    Send UDP packets to the given port and network interface. Values are
    generated by the specified generator.

    Keyword Args:
        interface (str): The send interface. Defaults to "localhost".
        port (int): The send port. Defaults to 51002.
        generator (generator): A generator function that returns messages to be
        sent as UDP packets. Defaults to sequential integers.

    Returns:
        None
    """
    global should_run_arr
    # Create a UDP socket
    sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)

    for val in generator():
        if not should_run_arr[should_run_index]:
            break

        # Send the message as a UDP packet
        sock.sendto(val, (interface, port))
        # Wait for 1 millisecond before sending the next message
        # Changed to 10 milisecond for CI/CD pipeline
        time.sleep(.010)

    print("UDP packet sending stopped.")
    sock.close()


